NG.parseMap = function (rows) {
  var h = rows.length;
  var w = rows[0].length;
  var tiles = [];
  var shrines = [];
  var gates = {};
  var spawn = { x: 2, y: 2 };
  var portal = null;
  var certDoor = null;
  var fountain = null;
  for (var y = 0; y < h; y++) {
    var row = [];
    var line = rows[y];
    for (var x = 0; x < w; x++) {
      var ch = line[x] || "#";
      row.push(ch);
      if (ch === "@") spawn = { x: x, y: y };
      if (ch === "P") portal = { x: x, y: y };
      if (ch === "*") shrines.push({ x: x, y: y, index: shrines.length });
      if (ch === "X") certDoor = { x: x, y: y };
      if (ch === "F") fountain = { x: x, y: y };
      if (ch >= "1" && ch <= "7") gates[ch.charCodeAt(0) - 49] = { x: x, y: y };
    }
    tiles.push(row);
  }
  return { w: w, h: h, tiles: tiles, spawn: spawn, portal: portal, shrines: shrines, gates: gates, certDoor: certDoor, fountain: fountain };
};

